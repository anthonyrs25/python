precios = [-2,0,1,4,5]

# calcular el promedio de una lista

print(sum(precios)) # suma de la lista
print(len(precios)) # cantidad de ítems
print((sum(precios)/len(precios))) # dividir la suma para la cantidad

# redondear el promedio

print(round((sum(precios)/len(precios))))

# redondear con dos decimales

print(round((sum(precios)/len(precios)), 2))
